def plus_lines() -> str:
    return "\n".join(
        line[1:]
        for line in PATCH.read_text(encoding="utf-8").splitlines()
        if line.startswith("+") and not line.startswith("+++")
    )


def patched_hunks() -> str:
    """The patched side of every hunk: context and added lines."""
    hunks = PATCH.read_text(encoding="utf-8").split("\n@@", 1)[1]
    return "\n".join(
        line[1:]
        for line in hunks.splitlines()
        if line.startswith((" ", "+")) and not line.startswith("+++")
    )


def extract_c_block(source: str, start: str, end: str) -> str:
    begin = source.index(start)
    finish = source.index(end, begin) + len(end)
    return source[begin:finish]


